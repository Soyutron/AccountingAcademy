#!/usr/bin/env bash
# 統合後の再検証。mainでIssueの回帰テスト(ファイル名にissue-<n> を含むもの)を単体で実行し、
# 通ればagent:verifiedを付けて検証済みコメント、落ちればIssueをreopenしてagent:needs-humanを付ける。
# 設計はdocs/quality-loop.md §4.5。issue-agent.shの最後から呼ばれるほか、手でも実行できる。
#   scripts/issue-verify.sh <Issue番号>
set -u
cd "$(dirname "$0")/.."
ISSUE="${1:?Issue番号を指定してください}"
LOG_DIR="${ISSUE_LOG_DIR:-logs/issue-agent}/$ISSUE"
mkdir -p "$LOG_DIR"
log() { echo "[$(date '+%H:%M:%S')] verify: $*"; }
note() { printf '> *This was generated by AI (issue-verify).*\n\n%s\n' "$1" | gh issue comment "$ISSUE" --body-file - >/dev/null; }

[ "$(git branch --show-current)" = "main" ] || { log "mainではありません"; exit 5; }
mapfile -t files < <(git ls-files | grep -E "issue-$ISSUE(\.|-)" | grep -E '\.(spec|test)\.tsx?$')
if [ "${#files[@]}" -eq 0 ]; then
  log "回帰テストが見つかりません(issue-${ISSUE}を名前に含むspec / test)"
  note "再検証: 回帰テスト(ファイル名に \`issue-$ISSUE\` を含むspec / test)がmainに見つからないため、自動の再検証は行っていません。"
  exit 1
fi
# 開発サーバーのvelite --watchはマージ途中の状態で再構築に失敗して .velite/ を古いまま残すことがあるので、テストの前に作り直す
log "pnpm content"
pnpm content >"$LOG_DIR/verify.log" 2>&1 || { note "再検証: mainのコンテンツ検査に失敗しました(\`$LOG_DIR/verify.log\`)"; exit 1; }
# E2Eは本番ビルドを起動するので、統合後のmainを必ずビルドし直す(古い .nextを配ると修正前の挙動を検証してしまう)
# ポートは並走するissue-agentの関門(3100〜)と重ならないものを使う
if printf '%s\n' "${files[@]}" | grep -q '^e2e/'; then
  log "pnpm build"
  pnpm build >>"$LOG_DIR/verify.log" 2>&1 || { note "再検証: mainのビルドに失敗しました(\`$LOG_DIR/verify.log\`)"; exit 1; }
fi
rc=0
for f in "${files[@]}"; do
  log "実行: $f"
  case "$f" in
    e2e/*) (E2E_SERVER=start E2E_PORT=3190 pnpm exec playwright test "$f") >>"$LOG_DIR/verify.log" 2>&1 || rc=1 ;;
    *) (pnpm vitest run "$f") >>"$LOG_DIR/verify.log" 2>&1 || rc=1 ;;
  esac
done
sha=$(git rev-parse --short HEAD)
if [ "$rc" -eq 0 ]; then
  gh issue edit "$ISSUE" --add-label agent:verified --remove-label agent:needs-human >/dev/null
  note "再検証: main \`$sha\` で回帰テスト($(printf '`%s` ' "${files[@]}"))が通りました。"
  # 以前の再検証でreopenされていれば閉じ直す
  [ "$(gh issue view "$ISSUE" --json state --jq .state)" = "OPEN" ] && gh issue close "$ISSUE" >/dev/null
  log "通過($sha)"
else
  gh issue reopen "$ISSUE" >/dev/null 2>&1
  gh issue edit "$ISSUE" --add-label agent:needs-human --remove-label agent:verified >/dev/null
  note "再検証: main \`$sha\` で回帰テストが **失敗** しました($(printf '`%s` ' "${files[@]}"))。reopenしました。ログ: \`$LOG_DIR/verify.log\`

\`\`\`
$(tail -n 40 "$LOG_DIR/verify.log")
\`\`\`"
  log "失敗($sha)。reopenしました"
fi
exit $rc
