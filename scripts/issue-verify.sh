#!/usr/bin/env bash
# 統合後の再検証。main で Issue の回帰テスト(ファイル名に issue-<n> を含むもの)を単体で実行し、
# 通れば agent:verified を付けて検証済みコメント、落ちれば Issue を reopen して agent:needs-human を付ける。
# 設計は docs/quality-loop.md §4.5。issue-agent.sh の最後から呼ばれるほか、手でも実行できる。
#   scripts/issue-verify.sh <Issue 番号>
set -u
cd "$(dirname "$0")/.."
ISSUE="${1:?Issue 番号を指定してください}"
LOG_DIR="${ISSUE_LOG_DIR:-logs/issue-agent}/$ISSUE"
mkdir -p "$LOG_DIR"
log() { echo "[$(date '+%H:%M:%S')] verify: $*"; }
note() { printf '> *This was generated by AI (issue-verify).*\n\n%s\n' "$1" | gh issue comment "$ISSUE" --body-file - >/dev/null; }

[ "$(git branch --show-current)" = "main" ] || { log "main ではありません"; exit 5; }
mapfile -t files < <(git ls-files | grep -E "issue-$ISSUE(\.|-)" | grep -E '\.(spec|test)\.tsx?$')
if [ "${#files[@]}" -eq 0 ]; then
  log "回帰テストが見つかりません(issue-$ISSUE を名前に含む spec / test)"
  note "再検証: 回帰テスト(ファイル名に \`issue-$ISSUE\` を含む spec / test)が main に見つからないため、自動の再検証は行っていません。"
  exit 1
fi
rc=0
for f in "${files[@]}"; do
  log "実行: $f"
  case "$f" in
    e2e/*) (E2E_SERVER=start E2E_PORT=3102 pnpm exec playwright test "$f") >>"$LOG_DIR/verify.log" 2>&1 || rc=1 ;;
    *) (pnpm vitest run "$f") >>"$LOG_DIR/verify.log" 2>&1 || rc=1 ;;
  esac
done
sha=$(git rev-parse --short HEAD)
if [ "$rc" -eq 0 ]; then
  gh issue edit "$ISSUE" --add-label agent:verified >/dev/null
  note "再検証: main \`$sha\` で回帰テスト($(printf '`%s` ' "${files[@]}"))が通りました。"
  log "通過($sha)"
else
  gh issue reopen "$ISSUE" >/dev/null 2>&1
  gh issue edit "$ISSUE" --add-label agent:needs-human --remove-label agent:verified >/dev/null
  note "再検証: main \`$sha\` で回帰テストが **失敗** しました($(printf '`%s` ' "${files[@]}"))。reopen しました。ログ: \`$LOG_DIR/verify.log\`

\`\`\`
$(tail -n 40 "$LOG_DIR/verify.log")
\`\`\`"
  log "失敗($sha)。reopen しました"
fi
exit $rc
