#!/usr/bin/env bash
# GitHub Issueを1件、実装側のモデルがworktreeで実装し、レビュー側のモデルが読み取り専用でレビューし、mainへ統合してpushする。
# 設計はdocs/quality-loop.md §4.4。続けて回すのはscripts/issue-loop.sh。元はTaxForgeのscripts/issue-agent.sh。
#
#   scripts/issue-agent.sh <Issue番号>   # 1件処理
#   scripts/issue-agent.sh status         # 処理中のIssueと残っているworktreeを表示
#
# 終了コード:
#   0 mainへ統合した
#   2人手が要る(実装で行き詰まり、レビューが収束しない、保護パス)。ループはこのIssueをスキップして次へ進む
#   3コンフリクト
#   4関門(scripts/check.sh)が上限回数まで通らない
#   5環境の問題(本体が汚れている、originより遅れている、claudeの異常終了、pushの失敗)。ループはこれで停止する
#   6対象外(openでない、処理中)
#   7 Claude Codeの利用上限。ループはリセットまで待って同じIssueを取り直す
# 2〜4ではworktreeとブランチを残し、Issueにagent:needs-humanを付ける。
#
# 環境変数:
#   ISSUE_MAX_ROUNDS      レビュー → 修正の上限(既定2)。関門の修正回数の上限も兼ねる
#   ISSUE_PHASE_TIMEOUT   claude -p 1回の上限秒(既定3600)
#   ISSUE_MAX_TURNS       claude -p 1回のターン上限(既定200)
#   ISSUE_MAX_BUDGET_USD  claude -p 1回の費用上限(未指定なら無し)
#   ISSUE_PUSH            統合後にmainをoriginへpushする(既定1。0で止める)
#   ISSUE_VERIFY          統合後にscripts/issue-verify.shを回す(既定1)
#   ISSUE_FORCE=1         agent:in-progress / agent:needs-humanが付いていても引き継ぐ
#   ISSUE_FRESH=1         既存のworktreeとブランチを捨てて作り直す
#   ISSUE_LOG_DIR         ログ置き場(既定logs/issue-agent)
#   ISSUE_E2E_PORT        関門のE2Eが本番ビルドを起動するポート(既定3100。issue-loopが並列のワーカーごとに変える)
#   ISSUE_IMPL_MODEL      実装側のモデル(既定opus)
#   ISSUE_REVIEW_MODEL    レビュー側のモデル(既定fable)
set -u
cd "$(dirname "$0")/.."
ROOT=$PWD

LOG_DIR="${ISSUE_LOG_DIR:-logs/issue-agent}"
case "$LOG_DIR" in /*) ;; *) LOG_DIR="$ROOT/$LOG_DIR" ;; esac
MAX_ROUNDS="${ISSUE_MAX_ROUNDS:-2}"
PHASE_TIMEOUT="${ISSUE_PHASE_TIMEOUT:-3600}"
MAX_TURNS="${ISSUE_MAX_TURNS:-200}"
BUDGET="${ISSUE_MAX_BUDGET_USD:-}"
PUSH="${ISSUE_PUSH:-1}"
VERIFY="${ISSUE_VERIFY:-1}"
IMPL_MODEL="${ISSUE_IMPL_MODEL:-opus}"
REVIEW_MODEL="${ISSUE_REVIEW_MODEL:-fable}"
PROMPT_DIR="$ROOT/scripts/issue-agent"
AI_NOTE="> *This was generated by AI (issue-agent).*"
# Bashの文字列を検査するPreToolUseフック(--disallowedToolsの前方一致を補う)
HOOK_SETTINGS="{\"hooks\":{\"PreToolUse\":[{\"matcher\":\"Bash\",\"hooks\":[{\"type\":\"command\",\"command\":\"$ROOT/scripts/issue-agent/guard.sh\"}]}]}}"

DISALLOWED=(
  "Bash(git push:*)" "Bash(git merge:*)" "Bash(git rebase:*)" "Bash(git checkout:*)" "Bash(git switch:*)"
  "Bash(git worktree:*)" "Bash(git branch -D:*)" "Bash(git reset --hard:*)"
  "Bash(gh issue close:*)" "Bash(gh issue delete:*)" "Bash(gh issue edit:*)" "Bash(gh pr:*)" "Bash(gh repo:*)" "Bash(gh api:*)"
  "Bash(supabase:*)" "Bash(npx supabase:*)" "Bash(pnpm db:reset:*)" "Bash(pnpm db:stop:*)"
  "mcp__playwright" "mcp__chrome-devtools" "mcp__shadcn"
)
# 未信頼ワークスペース扱いだとsettings.jsonのallowが効かないので、使う道具は明示的に許可する
IMPL_ALLOWED=("Bash" "Read" "Write" "Edit" "MultiEdit" "Glob" "Grep" "Agent" "Skill" "WebFetch" "mcp__next-devtools" "mcp__context7")
REVIEW_DISALLOWED=("Bash(git commit:*)" "Bash(git add:*)" "Bash(git restore:*)" "Bash(git stash:*)" "Bash(git reset:*)")
# 触れていたら人手に回すパス
PROTECTED_RE='^(supabase/migrations/|\.github/|\.githooks/|scripts/|\.claude/|Makefile$|velite\.config\.ts$)|(^|/)\.env(\..*)?$'

log() { echo "[$(date '+%H:%M:%S')] $*"; }

json_get() {
  python3 -c '
import json, sys
d = json.load(open(sys.argv[1]))
for k in sys.argv[2].split("."):
    d = d[int(k)] if isinstance(d, list) else d[k]
print(d if not isinstance(d, (dict, list)) else json.dumps(d, ensure_ascii=False, indent=2))
' "$1" "$2" 2>/dev/null
}

if [ "${1:-}" = "status" ]; then
  for label in agent:in-progress agent:needs-human; do
    echo "== $label"
    gh issue list --state open --label "$label" --json number,title --jq '.[] | "  #\(.number)\t\(.title)"' 2>/dev/null
  done
  echo "== 残っているworktree"; git worktree list | grep 'worktree-issue-' || echo "  なし"
  echo "== 動いているプロセス"; pgrep -af '^bash scripts/(issue-agent|issue-loop|triage-agent|quality-night)\.sh' | grep -v " status$" || echo "  なし"
  echo "== ログ: $LOG_DIR/<番号>/"
  exit 0
fi

ISSUE="${1:?Issue番号を指定してください(例: scripts/issue-agent.sh 12)}"
case "$ISSUE" in *[!0-9]*) echo "Issue番号は数字で指定してください: $ISSUE"; exit 6 ;; esac
ISSUE_DIR="$LOG_DIR/$ISSUE"
WT="$ROOT/.claude/worktrees/issue-$ISSUE"
BRANCH="worktree-issue-$ISSUE"
mkdir -p "$ISSUE_DIR"
exec > >(tee -a "$ISSUE_DIR/run.log") 2>&1
export ISSUE WT BRANCH MAX_ROUNDS
# 関門だけでなく、実装側のClaudeが自分で回すscripts/check.shも同じポートを使う(並走するワーカーと衝突させない)
export E2E_PORT="${ISSUE_E2E_PORT:-3100}"

# ロックはIssueごと(別のIssueとは並走できる)。mainへの統合は7で$LOG_DIR/lockにより直列化する
exec 9>"$ISSUE_DIR/lock"
flock -n 9 || { log "Issue #${ISSUE}は別のissue-agentが処理中です($ISSUE_DIR/lock)"; exit 6; }

comment() { printf '%s\n\n%s\n' "$AI_NOTE" "$1" | gh issue comment "$ISSUE" --body-file - >/dev/null; }

give_up() {
  local code=$1 label=$2 msg=$3
  log "中断: $msg"
  gh issue edit "$ISSUE" --remove-label agent:in-progress ${label:+--add-label "$label"} >/dev/null
  comment "issue-agentを中断しました(終了コード$code): $msg

worktree \`$WT\`(ブランチ \`$BRANCH\`)は残しています。ログ: \`$ISSUE_DIR/\`"
  exit "$code"
}

render() {
  CUTOFF=$(date -d "@$(( $(date +%s) + PHASE_TIMEOUT ))" '+%H:%M')
  export CUTOFF ROUND PLAN FINDINGS PREV_FINDINGS GATE_REPORT PREV_HEAD FIX_SUMMARY
  envsubst '$ISSUE $CUTOFF $WT $BRANCH $ROUND $MAX_ROUNDS $PLAN $FINDINGS $PREV_FINDINGS $GATE_REPORT $PREV_HEAD $FIX_SUMMARY' <"$1" >"$2"
}

# worktreeをcwdにしてclaude -pを実行し、結果JSONを書く。
#   run_claude <model> <結果JSON> <スキーマ> <プロンプト> [claudeへの追加フラグ...]
# 戻り値: 0成功 / 1 claudeの失敗 / 2利用上限 / 124タイムアウト
run_claude() {
  local model=$1 out=$2 schema=$3 prompt=$4 rc
  shift 4
  (cd "$WT" && timeout --foreground -k 30 "$PHASE_TIMEOUT" \
    claude -p "$(cat "$prompt")" --model "$model" \
      --permission-mode acceptEdits --max-turns "$MAX_TURNS" ${BUDGET:+--max-budget-usd "$BUDGET"} \
      --output-format json --json-schema "$(cat "$schema")" \
      --settings "$HOOK_SETTINGS" \
      "$@") >"$out" 2>"${out%.json}.stderr"
  rc=$?
  if [ "$(json_get "$out" is_error)" != "False" ] && scripts/claude-usage-limit.sh limited "$out" "${out%.json}.stderr"; then return 2; fi
  [ "$rc" -eq 124 ] && return 124
  [ "$rc" -ne 0 ] && return 1
  [ "$(json_get "$out" is_error)" = "False" ] || return 1
  [ -n "$(json_get "$out" structured_output)" ] || return 1
  return 0
}

claude_or_die() {
  case $1 in
    0) ;;
    2) give_up 7 "" "$2: Claude Codeの利用上限に達しました。リセット後に取り直します" ;;
    124) give_up 2 agent:needs-human "$2: ${PHASE_TIMEOUT}秒で打ち切られました" ;;
    *) give_up 5 "" "$2: claudeが異常終了しました(ログ$ISSUE_DIR/)" ;;
  esac
}

run_impl() {
  local phase=$1 template=$2 out=$3
  render "$template" "${out%.json}.prompt.md"
  log "$phase($IMPL_MODEL、上限${PHASE_TIMEOUT}s)"
  run_claude "$IMPL_MODEL" "$out" "$PROMPT_DIR/impl.schema.json" "${out%.json}.prompt.md" \
    --resume "$SESSION" --allowedTools "${IMPL_ALLOWED[@]}" --disallowedTools "${DISALLOWED[@]}"
  claude_or_die $? "$phase"
  SESSION=$(json_get "$out" session_id)
  if [ "$(json_get "$out" structured_output.status)" != "done" ]; then
    give_up 2 agent:needs-human "${phase}で行き詰まりました: $(json_get "$out" structured_output.summary)"
  fi
}

# 関門。0通過 / 1直せる失敗 / 2保護パスへの変更。理由はGATE_REPORT。
gate() {
  local dirty protected checklog="$ISSUE_DIR/check-$1.log"
  GATE_REPORT=""
  dirty=$(git -C "$WT" status --porcelain)
  if [ -n "$dirty" ]; then GATE_REPORT="未コミットの変更が残っています:
$dirty"; return 1; fi
  if [ -z "$(git -C "$WT" diff --stat main...HEAD)" ]; then GATE_REPORT="mainとの差分がありません(何も実装されていません)"; return 1; fi
  protected=$(git -C "$WT" diff --name-only main...HEAD | grep -E "$PROTECTED_RE")
  if [ -n "$protected" ]; then GATE_REPORT="保護パスに変更があります:
$protected"; return 2; fi
  if ! git -C "$WT" diff --name-only main...HEAD | grep -q "issue-$ISSUE"; then
    GATE_REPORT="回帰テストがありません(ファイル名にissue-${ISSUE}を含むテストをe2e/repro/ かsrc/lib/ に追加してください)"; return 1
  fi
  # 実装側・レビュー側のClaudeが起動したまま残した、このworktreeの本番サーバーは止める(ポートを塞ぎ続ける)
  local p
  for p in $(ss -ltnp 2>/dev/null | grep ":$E2E_PORT " | grep -oP 'pid=\K[0-9]+' | sort -u); do
    [ "$(readlink /proc/"$p"/cwd 2>/dev/null)" = "$WT" ] && { log "ポート${E2E_PORT}に残っていたこのworktreeのサーバー(pid $p)を止めます"; kill "$p"; }
  done
  # 別のプロセスが同じポートでE2Eを回している最中なら、空くまで待つ(最大10分)
  local waited=0
  while ss -ltn 2>/dev/null | grep -q ":$E2E_PORT "; do
    [ "$waited" -gt 0 ] || log "E2Eのポート${E2E_PORT}が使用中です。空くまで待ちます"
    sleep 10; waited=$((waited + 10)); [ "$waited" -lt 600 ] || break
  done
  log "scripts/check.sh($checklog)"
  if ! (cd "$WT" && scripts/check.sh) >"$checklog" 2>&1; then
    GATE_REPORT="scripts/check.shが失敗しました。出力の末尾:
$(tail -n 80 "$checklog")"; return 1
  fi
  return 0
}

findings_md() {
  python3 -c '
import json, sys
for f in json.load(open(sys.argv[1]))["structured_output"].get("findings", []):
    loc = f["file"] + (":%d" % f["line"] if f.get("line") else "")
    print("- **%s** `%s` %s" % (f["severity"], loc, f["issue"]))
    if f.get("suggestion"):
        print("  - 提案: %s" % f["suggestion"])
' "$1"
}
must_count() {
  python3 -c '
import json, sys
print(sum(1 for f in json.load(open(sys.argv[1]))["structured_output"].get("findings", []) if f["severity"] == "must"))
' "$1"
}
total_cost() {
  python3 -c '
import glob, json, sys
total = 0.0
for p in glob.glob(sys.argv[1] + "/*.json"):
    try: total += float(json.load(open(p)).get("total_cost_usd") or 0)
    except Exception: pass
print(f"{total:.2f}")
' "$ISSUE_DIR"
}

# ---------- 0. 前提確認とclaim ----------
[ "$(git branch --show-current)" = "main" ] || { log "本体チェックアウトがmainではありません"; exit 5; }
# 人が同時に別のファイルを編集していてもよい。統合で触るファイルと重なるときだけ止める(統合の直前に確かめる)
[ -z "$(git status --porcelain)" ] || log "注意: 本体チェックアウトに未コミットの変更があります。統合で触るファイルと重なれば中断します"
for cmd in claude gh pnpm envsubst python3; do command -v "$cmd" >/dev/null || { log "${cmd}が見つかりません"; exit 5; }; done
if [ "$PUSH" = 1 ]; then
  git fetch -q origin main || { log "originからmainを取得できません"; exit 5; }
  git merge-base --is-ancestor origin/main main || { log "ローカルのmainがorigin/mainより遅れています。先にpullしてください(pushしないならISSUE_PUSH=0)"; exit 5; }
fi

gh issue view "$ISSUE" --json state,title,labels >"$ISSUE_DIR/issue.json" || { log "Issue #${ISSUE}を取得できません"; exit 6; }
state=$(json_get "$ISSUE_DIR/issue.json" state)
title=$(json_get "$ISSUE_DIR/issue.json" title)
labels=$(gh issue view "$ISSUE" --json labels --jq '[.labels[].name] | join(" ")')
[ "$state" = "OPEN" ] || { log "Issue #${ISSUE}はopenではありません($state)"; exit 6; }
case " $labels " in
  *" agent:in-progress "*|*" agent:needs-human "*)
    [ "${ISSUE_FORCE:-0}" = 1 ] || { log "Issue #${ISSUE}は処理中か人手待ちです($labels)。引き継ぐならISSUE_FORCE=1"; exit 6; } ;;
esac
log "Issue #$ISSUE: $title"
gh issue edit "$ISSUE" --add-label agent:in-progress --remove-label agent:needs-human >/dev/null \
  || { log "ラベルを付けられません。scripts/labels.shを先に実行してください"; exit 5; }

# ---------- 1. worktree ----------
if [ -d "$WT" ] && [ "${ISSUE_FRESH:-0}" = 1 ]; then
  log "既存のworktreeを捨てます: $WT"; git worktree remove --force "$WT" && git branch -D "$BRANCH"
fi
if [ -d "$WT" ]; then log "既存のworktreeを再利用します: $WT"
elif git show-ref --verify --quiet "refs/heads/$BRANCH"; then git worktree add "$WT" "$BRANCH" || give_up 5 "" "worktreeを作れませんでした"
else git worktree add -b "$BRANCH" "$WT" main || give_up 5 "" "worktreeを作れませんでした"; fi
# .env.localはローカルSupabaseのキー(Claudeはsettingsのdenyで読めない)
[ -f .env.local ] && cp .env.local "$WT/.env.local"
log "依存を導入します($ISSUE_DIR/setup.log)"
(cd "$WT" && pnpm install --frozen-lockfile && pnpm content) >"$ISSUE_DIR/setup.log" 2>&1 || give_up 5 "" "依存の導入に失敗しました($ISSUE_DIR/setup.log)"

# ---------- 2〜3. 調査・計画・実装 ----------
ROUND=0 PLAN="" FINDINGS="" PREV_FINDINGS="" GATE_REPORT="" PREV_HEAD="" FIX_SUMMARY=""
render "$PROMPT_DIR/work.md" "$ISSUE_DIR/work.prompt.md"
log "調査・計画・実装($IMPL_MODEL、上限${PHASE_TIMEOUT}s)"
run_claude "$IMPL_MODEL" "$ISSUE_DIR/work.json" "$PROMPT_DIR/work.schema.json" "$ISSUE_DIR/work.prompt.md" --allowedTools "${IMPL_ALLOWED[@]}" --disallowedTools "${DISALLOWED[@]}"
claude_or_die $? "調査・計画・実装"
SESSION=$(json_get "$ISSUE_DIR/work.json" session_id)
case "$(json_get "$ISSUE_DIR/work.json" structured_output.status)" in
  done) ;;
  needs_human) give_up 2 agent:needs-human "人手が必要と判断しました: $(json_get "$ISSUE_DIR/work.json" structured_output.summary)" ;;
  *) give_up 2 agent:needs-human "実装で行き詰まりました: $(json_get "$ISSUE_DIR/work.json" structured_output.summary)" ;;
esac
PLAN=$(json_get "$ISSUE_DIR/work.json" structured_output.plan)

# ---------- 4〜6. 関門 → レビュー → 修正 ----------
round=1 gate_fails=0
while :; do
  ROUND=$round
  gate "$round.$gate_fails"; grc=$?
  if [ "$grc" -eq 2 ]; then give_up 2 agent:needs-human "$GATE_REPORT"; fi
  if [ "$grc" -ne 0 ]; then
    log "関門で失敗: ${GATE_REPORT%%$'\n'*}"
    gate_fails=$((gate_fails + 1))
    [ "$gate_fails" -le "$MAX_ROUNDS" ] || give_up 4 agent:needs-human "関門が通りませんでした: ${GATE_REPORT%%$'\n'*}(詳細はログ)"
    run_impl "関門の修正(${gate_fails}回目)" "$PROMPT_DIR/gate.md" "$ISSUE_DIR/gate-fix-$gate_fails.json"
    continue
  fi

  head_before=$(git -C "$WT" rev-parse HEAD)
  review="$ISSUE_DIR/review-$round.json"
  template=review.md; [ "$round" -gt 1 ] && template=recheck.md
  render "$PROMPT_DIR/$template" "${review%.json}.prompt.md"
  log "レビュー(ラウンド$round、$REVIEW_MODEL、$template、上限${PHASE_TIMEOUT}s)"
  run_claude "$REVIEW_MODEL" "$review" "$PROMPT_DIR/review.schema.json" "${review%.json}.prompt.md" \
    --tools "Read,Grep,Glob,Bash" --allowedTools "Read,Grep,Glob,Bash" --disallowedTools "${DISALLOWED[@]}" "${REVIEW_DISALLOWED[@]}"
  claude_or_die $? "レビュー(ラウンド$round)"
  if [ "$(git -C "$WT" rev-parse HEAD)" != "$head_before" ] || [ -n "$(git -C "$WT" status --porcelain --untracked-files=no)" ]; then
    give_up 5 "" "レビュアーが作業ツリーを変更しました(ラウンド$round)"
  fi
  git -C "$WT" clean -fdq -e node_modules -e .env.local

  must=$(must_count "$review")
  log "レビュー(ラウンド$round): $(json_get "$review" structured_output.verdict)(must ${must}件)"
  if [ "$must" -eq 0 ]; then break; fi
  [ "$round" -lt "$MAX_ROUNDS" ] || give_up 2 agent:needs-human "レビューが${MAX_ROUNDS}ラウンドで収束しませんでした(must ${must}件)

$(findings_md "$review")"
  FINDINGS=$(json_get "$review" structured_output.findings)
  run_impl "修正(ラウンド$round)" "$PROMPT_DIR/fix.md" "$ISSUE_DIR/fix-$round.json"
  PREV_FINDINGS=$FINDINGS; PREV_HEAD=$head_before
  FIX_SUMMARY=$(json_get "$ISSUE_DIR/fix-$round.json" structured_output.summary)
  round=$((round + 1))
done

# ---------- 7. 統合 ----------
# mainの取り込みからpush・再検証までは1件ずつ。並走するissue-agentはここで順番を待つ
exec 8>"$LOG_DIR/lock"
flock -n 8 || { log "別のissue-agentの統合を待ちます($LOG_DIR/lock)"; flock 8; }
head_before=$(git -C "$WT" rev-parse HEAD)
log "mainを取り込みます"
if ! git -C "$WT" merge --no-edit main >"$ISSUE_DIR/merge.log" 2>&1; then
  git -C "$WT" merge --abort; give_up 3 agent:needs-human "mainの取り込みでコンフリクトしました($ISSUE_DIR/merge.log)"
fi
if [ "$(git -C "$WT" rev-parse HEAD)" != "$head_before" ]; then
  gate final || give_up 4 agent:needs-human "main取り込み後の関門で失敗しました: ${GATE_REPORT%%$'\n'*}(詳細はログ)"
fi
[ "$(git branch --show-current)" = "main" ] || give_up 5 "" "本体チェックアウトがmainではなくなっています"
overlap=$(comm -12 <(git status --porcelain | cut -c4- | sort) <(git diff --name-only main..."$BRANCH" | sort))
[ -z "$overlap" ] || give_up 5 "" "本体チェックアウトの未コミットの変更が統合するファイルと重なっています:
$overlap"
log "mainへマージします"
if ! git merge --no-ff --no-edit -m "$title (#$ISSUE)" \
    -m "issue-agentによる統合(実装$IMPL_MODEL、レビュー$REVIEW_MODEL、${round}ラウンド)。" "$BRANCH" >>"$ISSUE_DIR/merge.log" 2>&1; then
  git merge --abort; give_up 3 agent:needs-human "mainへのマージに失敗しました($ISSUE_DIR/merge.log)"
fi
merge_sha=$(git rev-parse --short HEAD)

# ---------- 8. 後片付け ----------
git worktree remove "$WT" || git worktree remove --force "$WT"
git branch -d "$BRANCH"
gh issue edit "$ISSUE" --remove-label agent:in-progress --remove-label ready-for-agent >/dev/null
cost=$(total_cost)
leftover=$(findings_md "$review")
pushed="pushは未実施(ISSUE_PUSH=0。pushするとCloses #${ISSUE}で閉じます)"
if [ "$PUSH" = 1 ]; then
  # pre-pushフック(lint / 型 / テスト)は関門で通したものと同じなので飛ばす
  if git push -q --no-verify origin main >>"$ISSUE_DIR/merge.log" 2>&1; then pushed="origin/mainへpush済み(Closes #${ISSUE}で閉じます)"
  else
    comment "## mainへ統合しました(pushは失敗)

マージコミット \`$merge_sha\` はローカルのmainに入っていますが、originへのpushに失敗しました($ISSUE_DIR/merge.log)。手でpushしてください。レビュー${round}ラウンド、費用表示 \$$cost。"
    log "完了(push失敗): $merge_sha"; exit 5
  fi
fi
comment "## mainへ統合しました

マージコミット \`$merge_sha\`(--no-ff、$pushed)。レビュー${round}ラウンド、費用表示 \$$cost。${leftover:+

残った指摘(should / nit):
$leftover}"
log "完了: $merge_sha($pushed、レビュー${round}ラウンド、費用表示 \$$cost)"
if [ "$VERIFY" = 1 ]; then scripts/issue-verify.sh "$ISSUE" || log "再検証で問題がありました(scripts/issue-verify.sh $ISSUE)"; fi
exit 0
